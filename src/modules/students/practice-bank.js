function mcq(text, correct, alternatives, explanation, index, section) {
  const options = [
    ...new Set([String(correct), ...alternatives.map(String)]),
  ].slice(0, 4);
  while (options.length < 4)
    options.push("None of the other listed values " + options.length);
  const rotate = index % options.length;
  const shuffled = options.slice(rotate).concat(options.slice(0, rotate));
  return {
    id: "q" + (index + 1),
    section,
    type: "mcq",
    question: text,
    options: shuffled,
    correctIndex: shuffled.indexOf(String(correct)),
    expectedPoints: [],
    marks: 1,
    explanation,
  };
}
export function practiceQuestions(category, level) {
  const name = CATEGORIES[category]?.name;
  if (!name) throw Error("Unknown practice category");
  if (category === "management-basics" || category === "business-communication")
    return (category === "management-basics" ? management : communication)[
      level - 1
    ].map(([text, options, explanation], index) =>
      mcq(text, options[0], options.slice(1), explanation, index, name),
    );
  return Array.from({ length: 8 }, (_, index) => {
    const n = index + 2,
      scale = level * 10,
      base = (n + level) * 100;
    if (category === "aptitude") {
      const percent = 5 * ((index % 4) + 1),
        growth = (base * (100 + percent)) / 100;
      const answer =
        level >= 4
          ? Number(((growth * (100 - percent)) / 100).toFixed(2))
          : level >= 2
            ? growth
            : (base * percent) / 100;
      return mcq(
        level >= 4
          ? `A value of ${base} rises ${percent}% and then falls ${percent}%. What is its final value?`
          : level >= 2
            ? `A value of ${base} increases by ${percent}%. What is the new value?`
            : `What is ${percent}% of ${base}?`,
        answer,
        [answer + scale, answer - scale, base],
        level >= 4
          ? `Multiply ${base} by ${1 + percent / 100} and then by ${1 - percent / 100}. Equal percentage rises and falls do not cancel.`
          : `Convert the percentage to a fraction of 100, then apply it to ${base}.`,
        index,
        name,
      );
    }
    if (category === "reasoning") {
      const ratio = level >= 3 ? 3 : 2,
        start = n + level,
        sequence =
          level >= 3
            ? [start, start * ratio, start * ratio ** 2, start * ratio ** 3]
            : [start, start + scale, start + 2 * scale, start + 3 * scale];
      const answer = level >= 3 ? start * ratio ** 4 : start + 4 * scale;
      return mcq(
        `What comes next in the sequence ${sequence.join(", ")}, ?`,
        answer,
        [answer + scale, answer - 1, answer + start],
        level >= 3
          ? `Each term is multiplied by ${ratio}.`
          : `Each term increases by ${scale}.`,
        index,
        name,
      );
    }
    if (category === "data-interpretation") {
      const north = base,
        south = base + scale * 5,
        total = north + south;
      const answer =
        level >= 3
          ? Number((((south - north) / north) * 100).toFixed(2))
          : total;
      return mcq(
        `Quarterly revenue (units): North ${north}; South ${south}. ${level >= 3 ? "By what percentage does South exceed North? Round to two decimal places." : "What is combined revenue?"}`,
        answer,
        [answer + 5, answer + 10, answer - 5],
        level >= 3
          ? `Use (South − North) ÷ North × 100, not the combined total as denominator.`
          : `Add ${north} and ${south}.`,
        index,
        name,
      );
    }
    const price = 100 + scale,
      variable = 40 + index * 2,
      fixed = (index + 3) * 1000,
      contribution = price - variable;
    const answer = level >= 3 ? Math.ceil(fixed / contribution) : contribution;
    return mcq(
      `A business sells a unit for ₹${price}, with variable cost ₹${variable} and fixed cost ₹${fixed}. ${level >= 3 ? "What is the minimum whole number of units needed to break even?" : "What is contribution per unit?"}`,
      answer,
      [answer + 10, Math.max(0, answer - 5), answer + 1],
      level >= 3
        ? `Contribution is ₹${contribution}; divide fixed cost by contribution and round upward to whole units.`
        : `Contribution equals selling price minus variable cost: ${price} − ${variable}.`,
      index,
      name,
    );
  });
}
